// Real Workers/D1 integration. Run against an isolated local dev server only.
import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import {createHash} from 'node:crypto';
const origin=process.env.TEST_ORIGIN||'http://127.0.0.1:5173';
if(!['127.0.0.1','localhost'].includes(new URL(origin).hostname))throw Error('Teste restrito ao ambiente local.');
const login=await fetch(origin+'/signin-with-chatgpt?return_to=/admin',{redirect:'manual'});
const cookie=login.headers.get('set-cookie')?.split(';')[0];assert.ok(cookie);
const headers={cookie,origin,'Content-Type':'image/png'};
const fixture=new Uint8Array(await readFile(new URL('../public/og.png',import.meta.url)));
const bytes=new Uint8Array(5*1024*1024);bytes.set(fixture);
const upload=await fetch(origin+'/api/upload',{method:'POST',headers,body:bytes});
assert.equal(upload.status,200,await upload.clone().text());
const {url}=await upload.json();
const response=await fetch(origin+url);assert.equal(response.status,200);
const actual=Buffer.from(await response.arrayBuffer());
const hash=data=>createHash('sha256').update(data).digest('hex');
assert.equal(hash(actual),hash(bytes));
assert.equal(response.headers.get('content-type'),'image/png');
assert.equal(response.headers.get('x-content-type-options'),'nosniff');
const head=await fetch(origin+url,{method:'HEAD'});assert.equal(head.status,200);assert.equal(Number(head.headers.get('content-length')),bytes.length);
const cached=await fetch(origin+url,{headers:{'If-None-Match':response.headers.get('etag')}});assert.equal(cached.status,304);
const over=await fetch(origin+'/api/upload',{method:'POST',headers,body:new Uint8Array(bytes.length+1)});assert.equal(over.status,413);
const missing=await fetch(origin+'/api/images/'+crypto.randomUUID());assert.equal(missing.status,404);
const chunks=new ReadableStream({start(c){c.enqueue(bytes);c.enqueue(new Uint8Array(1));c.close()}});
const chunked=await fetch(origin+'/api/upload',{method:'POST',headers,body:chunks,duplex:'half'});assert.equal(chunked.status,413);
await mkdir(new URL('../test-results/',import.meta.url),{recursive:true});
await writeFile(new URL('../test-results/media-roundtrip.json',import.meta.url),JSON.stringify({url,sha256:hash(bytes),size:bytes.length},null,2));
console.log('PASS: upload D1 de 5 MB, SHA-256 idêntico, HEAD, ETag/304, MIME, nosniff, limites com/sem Content-Length e 404.');
